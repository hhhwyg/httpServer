#!/usr/bin/env python3
"""Build complete, disjoint WOFF2 subsets from the pinned Noto Sans SC source."""

import argparse
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


SOURCE_BLOB = "5371a543be5fc670c7cdee9760c03554ee3e9b8e"


def unicode_ranges(codepoints):
    ordered = sorted(codepoints)
    groups = []
    start = end = ordered[0]
    for value in ordered[1:]:
        if value == end + 1:
            end = value
        else:
            groups.append((start, end))
            start = end = value
    groups.append((start, end))
    return ", ".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in groups
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    source_data = args.source.read_bytes()
    blob = hashlib.sha1(f"blob {len(source_data)}\0".encode() + source_data).hexdigest()
    if blob != SOURCE_BLOB:
        raise ValueError("The input is not the pinned upstream Sans2.004 font")
    output = Path(__file__).resolve().parent
    source_font = TTFont(args.source)
    available = set(source_font.getBestCmap())
    source_font.close()
    latin = {cp for cp in available if cp < 0x300 or 0x2000 <= cp <= 0x206F or 0x20A0 <= cp <= 0x20CF}
    common = {cp for cp in available if 0x3000 <= cp <= 0x303F or 0xFF00 <= cp <= 0xFFEF}
    for first in range(0xB0, 0xD8):
        for second in range(0xA1, 0xFF):
            try:
                common.add(ord(bytes((first, second)).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    common &= available
    common -= latin
    remaining = sorted(available - latin - common)
    common_ordered = sorted(common)
    groups = [("latin", latin)]
    groups.extend((f"common-{index // 1024:02d}", set(common_ordered[index:index + 1024])) for index in range(0, len(common_ordered), 1024))
    groups.extend((f"extended-{index // 512:02d}", set(remaining[index:index + 512])) for index in range(0, len(remaining), 512))
    css = ["/* Noto Sans SC 2.004, SIL OFL 1.1. Generated by build_subsets.py. */"]
    manifest = {"source_blob_sha1": blob, "source_sha256": hashlib.sha256(source_data).hexdigest(), "unicode_count": len(available), "subsets": []}
    seen = set()
    for name, codepoints in groups:
        filename = f"noto-sans-sc-{name}.woff2"
        if not (output / filename).exists():
            font = TTFont(args.source, recalcTimestamp=False)
            options = subset.Options()
            options.layout_features = ["*"]
            options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17, 25]
            options.name_languages = ["*"]
            worker = subset.Subsetter(options=options)
            worker.populate(unicodes=codepoints)
            worker.subset(font)
            font.flavor = "woff2"
            font.save(output / filename)
            font.close()
        with TTFont(output / filename) as result:
            actual = set(result.getBestCmap())
            if codepoints != actual or seen & codepoints:
                raise ValueError(f"Invalid or overlapping subset {name}")
            if [(axis.minValue, axis.maxValue) for axis in result["fvar"].axes] != [(100.0, 900.0)]:
                raise ValueError(f"Variable weight axis lost in {name}")
            if "Adobe" not in result["name"].getDebugName(0) or "SIL Open Font License" not in result["name"].getDebugName(13):
                raise ValueError(f"License metadata lost in {name}")
        seen |= codepoints
        size = (output / filename).stat().st_size
        if size >= 1024 * 1024:
            raise ValueError(f"Subset {name} exceeds the default server output limit")
        ranges = unicode_ranges(codepoints)
        css.append(f'@font-face {{\n  font-family: "Noto Sans SC";\n  font-style: normal;\n  font-weight: 100 900;\n  font-display: swap;\n  src: local("Noto Sans SC"), url("./{filename}") format("woff2");\n  unicode-range: {ranges};\n}}')
        manifest["subsets"].append({"file": filename, "bytes": size, "unicode_count": len(codepoints), "unicode_range": ranges})
        print(f"{filename}: {size:,} bytes, {len(codepoints):,} codepoints", flush=True)
    if seen != available:
        raise ValueError("Unicode coverage differs from source")
    (output / "fonts.css").write_text("\n\n".join(css) + "\n", encoding="utf-8")
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Complete: {len(groups)} subsets, {len(seen):,} codepoints, {sum(item['bytes'] for item in manifest['subsets']):,} bytes")


if __name__ == "__main__":
    main()
